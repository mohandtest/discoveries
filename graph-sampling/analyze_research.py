#!/usr/bin/env python3
"""Recompute result tables from saved JSON (no external libraries required)."""
import json
from pathlib import Path


def main():
    lines = ['# Measured results', '', 'Generated by `python3 analyze_research.py`; see `STUDY_REPORT.md` for interpretation.', '',
             '## Public networks', '',
             'Four chains × 200 retained draws per row. ± denotes between-chain Monte Carlo SE, excluding bias.', '',
             '| Dataset | Budget | Engine | Observed triangles | Null mean ± MCSE | Upper tail | Tail MCSE |',
             '| --- | --- | --- | ---: | ---: | ---: | ---: |']
    study = json.loads(Path('results/public_study/summary.json').read_text())
    for r in study['runs']:
        t = r['statistics']['triangles']
        se = 'unknown (zero hits)' if t['mcse_tail'] is None else f"{t['mcse_tail']:.4f}"
        lines.append(f"| {r['dataset']} | {r['budget']} | {r['engine']} | {r['observed']['triangles']} | {t['mean']:.4f} ± {t['mcse_mean']:.4f} | {t['upper_tail']:.4f} | {se} |")
    lines += ['', '## Exact production-kernel convergence', '',
              'Worst initial-state TV, after the specified number of attempted proposals. Probabilities propagated numerically from exact rational transition matrices.', '',
              '| Degrees | States | 5 attempts | 10 attempts | 50 attempts | 100 attempts |',
              '| --- | ---: | ---: | ---: | ---: | ---: |']
    for case in json.loads(Path('results/production_exact.json').read_text()):
        values = [max(r['tv'] for r in case['records'] if r['attempts']==step) for step in [5,10,50,100]]
        lines.append('| '+str(case['degrees'])+' | '+str(case['states'])+' | '+' | '.join(f'{v:.6g}' for v in values)+' |')
    lines += ['', '## Repeated-run calibration', '',
              'Each row has 100 replicates, four chains, 40 draws/chain, spacing one. Starts are triangle extrema in saved state order. Gate uses oracle knowledge to omit exactly constant statistics. Coverage is for the exact triangle mean using mean ± 3.182446 × chain-mean SE.', '',
              '| Case degrees | Burn | Start index | Time-averaged TV | Covered /100 | Gate passes /100 | Uncovered among passes |',
              '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    cal = json.loads(Path('results/calibration/summary.json').read_text())
    keys = sorted({(r['case'],r['burn'],r['start']) for r in cal['results']})
    for key in keys:
        group = [r for r in cal['results'] if (r['case'],r['burn'],r['start'])==key]
        first = group[0]
        lines.append(f"| {first['degrees']} | {key[1]} | {key[2]} | {first['exact_time_averaged_tv']:.6g} | {sum(r['covered'] for r in group)} | {sum(r['gate_pass'] for r in group)} | {sum(r['gate_pass'] and not r['covered'] for r in group)} |")
    Path('results/MEASURED_RESULTS.md').write_text('\n'.join(lines)+'\n')


if __name__=='__main__':
    main()
